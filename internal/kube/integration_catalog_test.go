package kube

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

var updateCatalog = flag.Bool("update-catalog", false, "rewrite the frontend's generated integration catalog")

// integrationCatalogTS is the frontend copy of integrationCatalog. The sidebar
// gates each view on its CRD, ResourceView includes every view, and the view
// and detail registries are typed over it, so a catalog entry without a list
// view or detail decision fails the frontend typecheck.
var integrationCatalogTS = filepath.Join("..", "..", "frontend", "src", "lib", "integrationCatalog.generated.ts")

func renderIntegrationCatalog() string {
	var b strings.Builder
	b.WriteString("// Generated by go test ./internal/kube -run TestIntegrationCatalogIsCurrent -update-catalog.\n")
	b.WriteString("// Do not edit: the source is integrationCatalog in internal/kube/integration_conformance_test.go.\n")
	b.WriteString("export const INTEGRATION_RESOURCES = [\n")
	for _, r := range integrationCatalog {
		fmt.Fprintf(&b, "  { view: %q, group: %q, resource: %q, kind: %q, namespaced: %t },\n",
			r.view, r.gr.Group, r.gr.Resource, r.kind, r.namespaced)
	}
	b.WriteString("] as const\n\n")
	b.WriteString("export type IntegrationResource = (typeof INTEGRATION_RESOURCES)[number]\n")
	b.WriteString("export type IntegrationView = IntegrationResource['view']\n")
	return strings.ReplaceAll(b.String(), `"`, `'`)
}

func TestIntegrationCatalogIsCurrent(t *testing.T) {
	views := map[string]bool{}
	for _, r := range integrationCatalog {
		if r.view == "" || views[r.view] {
			t.Fatalf("view %q of %s is empty or used twice", r.view, r.gr)
		}
		views[r.view] = true
	}
	want := renderIntegrationCatalog()
	if *updateCatalog {
		if err := os.WriteFile(integrationCatalogTS, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(integrationCatalogTS)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("%s is stale; run go test ./internal/kube -run TestIntegrationCatalogIsCurrent -update-catalog", integrationCatalogTS)
	}
}
