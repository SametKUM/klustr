// Builds src/lib/api.generated.ts from the Wails v3 bindings that
// `wails3 generate bindings` writes to src/lib/wails/bindings: one camelCase
// entry per bound App method, wrapped by call() (src/lib/wailsCall.ts), and a
// Strict type alias per Go model.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const frontendDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const bindingsDir = path.join(frontendDir, 'src/lib/wails/bindings/klustr')
const servicePath = path.join(bindingsDir, 'app/app.ts')
const modelsRoot = path.join(bindingsDir, 'internal')
const outputPath = path.join(frontendDir, 'src/lib/api.generated.ts')

const serviceSource = await readFile(servicePath, 'utf8')
const bindingNames = [...serviceSource.matchAll(/^export function (\w+)\(/gm)].map(([, name]) => name)
if (bindingNames.length === 0) throw new Error(`No Wails bindings found in ${servicePath}`)

// Each Go package with models has its own models.ts; its directory name is the
// namespace (kube, update).
const namespaces = []
for (const entry of await readdir(modelsRoot, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  const modelsPath = path.join(modelsRoot, entry.name, 'models.ts')
  const source = await readFile(modelsPath, 'utf8').catch(() => null)
  if (source === null) continue
  const names = [...source.matchAll(/^export (?:interface|type|enum|class) (\w+)/gm)].map(([, name]) => name)
  if (names.length > 0) namespaces.push({ namespace: entry.name, names })
}
namespaces.sort((a, b) => a.namespace.localeCompare(b.namespace))
const models = namespaces.flatMap(({ namespace, names }) => names.map((name) => ({ namespace, name })))
if (models.length === 0) throw new Error(`No Wails models found under ${modelsRoot}`)

const lowerFirst = (value) => value[0].toLowerCase() + value.slice(1)
const upperFirst = (value) => value[0].toUpperCase() + value.slice(1)
const aliasFor = ({ namespace, name }) =>
  namespace === 'kube' ? name : `${upperFirst(namespace)}${name}`

const assertUnique = (values, label) => {
  const seen = new Set()
  for (const value of values) {
    if (seen.has(value)) throw new Error(`Duplicate generated ${label}: ${value}`)
    seen.add(value)
  }
}

assertUnique(bindingNames.map(lowerFirst), 'API method')
assertUnique(models.map(aliasFor), 'model alias')

const output = [
  '// Generated by npm run generate:api. Do not edit.',
  "import * as bindings from '@/lib/wails/bindings/klustr/app/app'",
  ...namespaces.map(
    ({ namespace }) =>
      `import type * as ${namespace} from '@/lib/wails/bindings/klustr/internal/${namespace}/models'`,
  ),
  "import { call, type Strict } from '@/lib/wailsCall'",
  '',
  ...models.map((model) => `export type ${aliasFor(model)} = Strict<${model.namespace}.${model.name}>`),
  '',
  'export const generatedApi = {',
  ...bindingNames.map((name) => `  ${lowerFirst(name)}: call(bindings.${name}),`),
  '}',
  '',
].join('\n')

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== output) {
    console.error('Generated API facade is stale. Run npm run generate:api.')
    process.exitCode = 1
  }
} else {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== output) await writeFile(outputPath, output)
}
